#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

function parseArgs(argv) {
  const out = { collection: '', out: '' };
  for (let i = 2; i < argv.length; i += 1) {
    const a = argv[i];
    if (a === '--collection') out.collection = argv[++i] || '';
    else if (a === '--out') out.out = argv[++i] || '';
  }
  return out;
}

function readText(file) {
  try { return fs.readFileSync(file, 'utf8'); } catch { return null; }
}

function readJson(file) {
  const t = readText(file);
  if (!t) return null;
  try { return JSON.parse(t); } catch { return null; }
}

function snippet(text, max = 1600) {
  if (!text) return '(missing)';
  return text.length > max ? `${text.slice(0, max)}\n...[truncated]` : text;
}

function fencedJson(obj) {
  if (!obj) return '```json\nnull\n```';
  return `\`\`\`json\n${JSON.stringify(obj, null, 2)}\n\`\`\``;
}

const args = parseArgs(process.argv);
if (!args.collection || !args.out) {
  console.error('Usage: node scripts/build-strong-model-prompt.mjs --collection ./collections/client-repo --out ./collections/client-repo/prompts');
  process.exit(1);
}

const collection = path.resolve(args.collection);
const outDir = path.resolve(args.out);
fs.mkdirSync(outDir, { recursive: true });

const files = {
  summary: path.join(collection, 'collection-summary.json'),
  analyze: path.join(collection, 'analyze.json'),
  readiness: path.join(collection, 'readiness.json'),
  env: path.join(collection, 'metadata', 'environment.json'),
  run: path.join(collection, 'metadata', 'run.json'),
  commands: path.join(collection, 'metadata', 'commands.json'),
  overview: path.join(collection, 'instructions-overview.md'),
};

const probeNames = ['flat-root', 'flat-areas', 'nested-root', 'nested-areas'];
const probes = probeNames.map((name) => ({
  name,
  status: readJson(path.join(collection, 'probes', name, 'status.json')),
  json: readText(path.join(collection, 'probes', name, 'probe.json')),
  stdout: readText(path.join(collection, 'probes', name, 'probe.stdout.log')),
  stderr: readText(path.join(collection, 'probes', name, 'stderr.log')),
}));

const generations = [
  {
    name: 'flat-root',
    status: readJson(path.join(collection, 'generated', 'flat-root', 'status.json')),
    output: readText(path.join(collection, 'generated', 'flat-root', 'copilot-instructions.generated.md')),
    stderr: readText(path.join(collection, 'generated', 'flat-root', 'stderr.log')),
  },
  {
    name: 'nested-root',
    status: readJson(path.join(collection, 'generated', 'nested-root', 'status.json')),
    output: readText(path.join(collection, 'generated', 'nested-root', 'AGENTS.generated.md')),
    stderr: readText(path.join(collection, 'generated', 'nested-root', 'stderr.log')),
  },
];

const contextCandidates = [
  'README.md', 'package.json', 'tsconfig.json', 'AGENTS.md', 'CLAUDE.md', 'CONTRIBUTING.md', 'SECURITY.md',
  '.github/copilot-instructions.md', 'CODEOWNERS',
];

const contextItems = contextCandidates.map((rel) => {
  const full = path.join(collection, 'context', rel);
  const content = readText(full);
  return { rel, content };
});

const synthesis = `# Strong-Model ADR Synthesis Prompt

You are producing a repo-specific AI Enablement ADR from an artifact bundle generated by a thin wrapper around microsoft/agentrc.

## Non-negotiables
- Treat agentrc outputs as evidence, not infallible truth.
- Separate facts, inferences, and unknowns.
- Dry-run outputs are suggestions, not validated instructions.
- Generated instruction files are candidate artifacts, not approved artifacts.
- Explicitly account for instruction-generation failures and diagnostics.
- Do not invent enterprise usage/adoption metrics.
- Recommend phased, constraint-first improvements.

## Bundle Metadata
### collection-summary.json
${fencedJson(readJson(files.summary))}

### metadata/run.json
${fencedJson(readJson(files.run))}

### metadata/environment.json
${fencedJson(readJson(files.env))}

### metadata/commands.json
${fencedJson(readJson(files.commands))}

## agentrc Core Artifacts
### analyze.json
${fencedJson(readJson(files.analyze))}

### readiness.json
${fencedJson(readJson(files.readiness))}

### instructions-overview.md
\`\`\`md
${readText(files.overview) ?? '(missing)'}
\`\`\`

## Dry-Run Probes
${probes.map((p) => `### Probe: ${p.name}
Status:
${fencedJson(p.status)}
Result JSON (if parse succeeded):
\`\`\`json
${p.json ?? '(missing)'}
\`\`\`
Stdout fallback (if non-JSON):
\`\`\`text
${snippet(p.stdout, 1200)}
\`\`\`
Stderr:
\`\`\`text
${snippet(p.stderr, 1200)}
\`\`\``).join('\n\n')}

## Real Generation Attempts
${generations.map((g) => `### Generation: ${g.name}
Status:
${fencedJson(g.status)}
Generated content (only if present):
\`\`\`md
${g.output ?? '(missing)'}
\`\`\`
Stderr snippet:
\`\`\`text
${snippet(g.stderr, 1200)}
\`\`\``).join('\n\n')}

## Context Files (best-effort copies)
${contextItems.map((c) => `### context/${c.rel}
\`\`\`text
${snippet(c.content, 1400)}
\`\`\``).join('\n\n')}

## Required Output
Produce a consulting-grade ADR using this sectioning:
- Title
- Status
- Date
- Repository
- Context
- Observed Facts
- Unknowns / Limits
- Current Engineering Maturity
- Current AI Enablement Maturity
- Governance / Constraints
- 8-Layer Maturity Interpretation
- Decision
- Recommended Next Investments (Instructions, Skills, Workflows, Governance/Guardrails, Learning/Upskilling)
- Suggested Artifacts to Add
- Experiments to Validate Improvement
- Success Metrics
- Risks / Caveats
- Consequences
- Follow-Up Checkpoints

Also explicitly answer:
1) what the repo appears to be
2) what low-tier outputs to keep/refine/replace/ignore
3) whether the repo is ready for instructions, skills, evals, workflows, MCP
4) first best next moves and learning priorities
`;

const review = `# Strong-Model ADR Review Prompt

You are reviewing a first-pass AI enablement ADR/recommendation set. Be adversarial, concrete, and evidence-anchored.

## Review Rules
- Identify unsupported claims.
- Identify generic filler or best-practice sludge.
- Identify recommendations too advanced for observed maturity.
- Identify where instruction-generation failures imply process risk.
- Identify where low-tier generated instructions should be rewritten or discarded.
- Distinguish facts vs inferences vs unknowns.
- Do not invent telemetry.

## Evidence Bundle Snapshot
### collection-summary.json
${fencedJson(readJson(files.summary))}

### instructions-overview.md
\`\`\`md
${readText(files.overview) ?? '(missing)'}
\`\`\`

### Generation failures (stderr snippets)
${generations.map((g) => `#### ${g.name}
\`\`\`text
${snippet(g.stderr, 1200)}
\`\`\``).join('\n\n')}

### Dry-run probe failure snippets
${probes.map((p) => `#### ${p.name}
\`\`\`text
${snippet(p.stderr, 1200)}
\`\`\``).join('\n\n')}

## Input To Review
Paste the first-pass ADR or recommendations below this line.

---
[PASTE FIRST-PASS ADR HERE]
---

## Required Output
Return exactly one of:
1) **Revised ADR** (full replacement), or
2) **Prioritized revision plan** with top issues first.

If you output a revision plan, include:
- claim to fix
- why it is weak
- evidence needed
- rewrite direction
- priority (P0/P1/P2)
`;

fs.writeFileSync(path.join(outDir, 'adr-synthesis-prompt.md'), synthesis);
fs.writeFileSync(path.join(outDir, 'adr-review-prompt.md'), review);
console.log(`Wrote prompts to ${outDir}`);
